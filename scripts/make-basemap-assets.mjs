#!/usr/bin/env node
// One-off generator for the distribution map's bundled basemap. Re-run only
// to pick up upstream style changes or rebuild the fonts; the outputs are
// committed.
//
//   node scripts/make-basemap-assets.mjs           # style template + sprite
//   node scripts/make-basemap-assets.mjs --glyphs  # ... plus Montserrat glyphs
//
// Outputs
//   basemap/style.template.json                    style template ({{assets}} placeholder)
//   basemap/sprite{,@2x}.{json,png}                city-dot icons
//   basemap/glyphs/<Font Name>/<range>.pbf         SDF glyphs (--glyphs only)
//
// Sources (see basemap/LICENSE.md)
//   style   CARTO Positron, github.com/CartoDB/basemap-styles (BSD-3-Clause)
//   tiles   GBIF OpenMapTiles vector tiles, tile.gbif.org
//   sprite  OpenMapTiles Positron, github.com/openmaptiles/positron-gl-style (BSD-3-Clause)
//   fonts   Montserrat, github.com/JulietaUla/Montserrat (SIL OFL 1.1)
//
// --glyphs needs `build_pbf_glyphs` on the PATH:
//   cargo install build_pbf_glyphs --version 1.5.1

import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BASEMAP = join(ROOT, "basemap");
const TEMPLATE = join(BASEMAP, "style.template.json");

const CARTO_STYLE =
  "https://raw.githubusercontent.com/CartoDB/basemap-styles/master/mapboxgl/positron.json";
const SPRITE = "https://openmaptiles.github.io/positron-gl-style/sprite";
const MONTSERRAT =
  "https://raw.githubusercontent.com/JulietaUla/Montserrat/master/fonts/ttf";
const GBIF_TILES = "https://tile.gbif.org/3857/omt/{z}/{x}/{y}.pbf";
const ATTRIBUTION =
  '<a href="https://www.gbif.org/citation-guidelines" target="_blank">GBIF</a> ' +
  '&copy; <a href="https://www.openmaptiles.org/copyright" target="_blank">OpenMapTiles</a> ' +
  '&copy; <a href="https://www.openstreetmap.org/copyright" target="_blank">OpenStreetMap contributors</a> ' +
  '&copy; <a href="https://carto.com/attributions" target="_blank">CARTO</a>';

// TTF file stem -> font name the style asks for.
const FONTS = {
  "Montserrat-Regular": "Montserrat Regular",
  "Montserrat-Medium": "Montserrat Medium",
  "Montserrat-Italic": "Montserrat Regular Italic",
  "Montserrat-MediumItalic": "Montserrat Medium Italic",
};
// Continent names at z0-2 clutter a distribution map.
const DROP_LAYERS = new Set(["place_continent"]);

const get = async (url) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res;
};

async function makeStyle() {
  const s = await (await get(CARTO_STYLE)).json();
  const sourceId = Object.keys(s.sources)[0];
  s.id = "col-positron";
  s.name = "COL Positron";
  s.metadata = {
    "col:source": CARTO_STYLE,
    "col:note": "Generated by scripts/make-basemap-assets.mjs. Do not edit by hand.",
  };
  s.sources = {
    openmaptiles: {
      type: "vector",
      tiles: [GBIF_TILES],
      minzoom: 0,
      maxzoom: 14,
      attribution: ATTRIBUTION,
    },
  };
  s.glyphs = "{{assets}}/glyphs/{fontstack}/{range}.pbf";
  s.sprite = "{{assets}}/sprite";
  const wanted = new Set(Object.values(FONTS));
  s.layers = s.layers
    .filter((l) => !DROP_LAYERS.has(l.id))
    .map((l) => {
      if (l.source === sourceId) l.source = "openmaptiles";
      const tf = l.layout?.["text-font"];
      // Static glyph hosting can't merge font stacks, so keep the first font.
      if (Array.isArray(tf)) {
        if (!wanted.has(tf[0])) throw new Error(`${l.id}: unexpected font ${tf[0]}`);
        l.layout["text-font"] = [tf[0]];
      }
      return l;
    });
  writeFileSync(TEMPLATE, JSON.stringify(s, null, 2) + "\n");
  console.log(`style template: ${s.layers.length} layers -> ${TEMPLATE}`);
}

async function makeSprite() {
  mkdirSync(BASEMAP, { recursive: true });
  for (const f of ["sprite.json", "sprite.png", "sprite@2x.json", "sprite@2x.png"]) {
    const url = SPRITE + f.slice("sprite".length);
    writeFileSync(join(BASEMAP, f), Buffer.from(await (await get(url)).arrayBuffer()));
  }
  console.log(`sprite -> ${BASEMAP}`);
}

async function makeGlyphs() {
  const tmp = mkdtempSync(join(tmpdir(), "col-glyphs-"));
  const ttf = join(tmp, "ttf");
  const out = join(tmp, "out");
  mkdirSync(ttf);
  for (const stem of Object.keys(FONTS)) {
    const buf = Buffer.from(await (await get(`${MONTSERRAT}/${stem}.ttf`)).arrayBuffer());
    writeFileSync(join(ttf, `${stem}.ttf`), buf);
  }
  execFileSync("build_pbf_glyphs", [ttf, out], { stdio: "inherit" });
  const glyphs = join(BASEMAP, "glyphs");
  rmSync(glyphs, { recursive: true, force: true });
  mkdirSync(glyphs, { recursive: true });
  for (const [stem, name] of Object.entries(FONTS)) {
    renameSync(join(out, stem), join(glyphs, name));
  }
  rmSync(tmp, { recursive: true, force: true });
  console.log(`glyphs -> ${glyphs}`);
}

await makeStyle();
await makeSprite();
if (process.argv.includes("--glyphs")) await makeGlyphs();
